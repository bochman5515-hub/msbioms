package msbioms.worldgen;

import com.mojang.datafixers.util.Pair;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.Climate;

import java.util.function.Consumer;

public class ModBiomeParameters {

    /**
     * Добавляет наши биомы в климатическую карту Overworld.
     */
    public static void addCustomBiomes(
            Consumer<Pair<Climate.ParameterPoint, ResourceKey<Biome>>> biomes
    ) {

        /*
         * ============================================================
         * СОЛЁНЫЙ КАМЕННЫЙ БЕРЕГ
         * ============================================================
         *
         * Это редкая разновидность каменистого побережья.
         *
         * Мы НЕ хотим полностью заменить vanilla stony_shore.
         *
         * Поэтому:
         *
         * 1. Сужаем диапазон температуры.
         * 2. Сужаем диапазон влажности.
         * 3. Делаем более узкую прибрежную область.
         * 4. Ограничиваем erosion.
         * 5. Depth оставляем около поверхности.
         *
         * В результате vanilla stony_shore будет встречаться
         * значительно чаще.
         */

        biomes.accept(
                Pair.of(
                        Climate.parameters(

                                // ------------------------------------------------
                                // TEMPERATURE
                                // ------------------------------------------------
                                //
                                // Только умеренный климат.
                                //
                                Climate.Parameter.span(
                                        -0.1F,
                                        0.35F
                                ),

                                // ------------------------------------------------
                                // HUMIDITY
                                // ------------------------------------------------
                                //
                                // Не слишком сухой и не слишком влажный берег.
                                //
                                Climate.Parameter.span(
                                        -0.35F,
                                        0.45F
                                ),

                                // ------------------------------------------------
                                // CONTINENTALNESS
                                // ------------------------------------------------
                                //
                                // Узкая зона непосредственно возле океана.
                                //
                                Climate.Parameter.span(
                                        -0.16F,
                                        -0.10F
                                ),

                                // ------------------------------------------------
                                // EROSION
                                // ------------------------------------------------
                                //
                                // Ограничиваем характер рельефа.
                                //
                                Climate.Parameter.span(
                                        -0.65F,
                                        -0.10F
                                ),

                                // ------------------------------------------------
                                // DEPTH
                                // ------------------------------------------------
                                //
                                // Только поверхность.
                                //
                                Climate.Parameter.point(
                                        0.0F
                                ),

                                // ------------------------------------------------
                                // WEIRDNESS
                                // ------------------------------------------------
                                //
                                // Не весь диапазон рельефа.
                                //
                                Climate.Parameter.span(
                                        -0.35F,
                                        0.35F
                                ),

                                // ------------------------------------------------
                                // OFFSET
                                // ------------------------------------------------
                                //
                                // Дополнительно немного отодвигаем наш биом
                                // от vanilla точек.
                                //
                                // Чем больше значение, тем менее охотно
                                // эта ParameterPoint выбирается.
                                //
                                0.15F
                        ),

                        ModBiomes.SALT_STONY_SHORE_KEY
                )
        );
    }
}